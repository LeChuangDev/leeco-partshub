import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const c = await b.newContext({ viewport: { width: 1440, height: 940 }, locale: 'zh-CN' })
const p = await c.newPage()
await p.goto('http://127.0.0.1:5173/#/dashboard'); await p.waitForTimeout(2400)
await p.getByRole('button', { name: '自定义' }).click(); await p.waitForTimeout(400)
const titles = async () => (await p.locator('.widget .w-title').allInnerTexts()).join(' / ')
console.log('before:', await titles())
const widgets = p.locator('.widget')
await widgets.nth(0).dragTo(widgets.nth(2))
await p.waitForTimeout(700)
console.log('after :', await titles())
const saved = await p.evaluate(() => localStorage.getItem('leeco_dash_layout_v1'))
console.log('saved :', saved?.slice(0, 160))
await p.reload(); await p.waitForTimeout(2400)
console.log('reload:', await titles())
await b.close()
