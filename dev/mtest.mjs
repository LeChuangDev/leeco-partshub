import { chromium } from 'playwright'
const BASE = 'http://127.0.0.1:5173'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1.25 })
const p = await ctx.newPage()
p.on('pageerror', e => console.log('ERR', e.message))
await p.goto(BASE + '/#/dashboard'); await p.waitForTimeout(2200)
const ids = await p.evaluate(async () => { const r = await fetch('/api/parts?pageSize=8'); const j = await r.json(); return j.data.list.map(x=>x.id) })
await p.goto(`${BASE}/#/labels?ids=${ids.join(',')}`); await p.waitForTimeout(2200)
const ov = await p.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth, sheet: document.querySelector('.sheet')?.getBoundingClientRect().width }))
console.log('labels overflow', JSON.stringify(ov))
await p.screenshot({ path: 'dev/.shots/r6-m-labels.png' })
await p.goto(BASE + '/#/bom'); await p.waitForTimeout(1400)
await p.getByRole('button', { name: '载入示例' }).click(); await p.waitForTimeout(300)
await p.getByRole('button', { name: '解析并匹配库存' }).click(); await p.waitForTimeout(2000)
const ov2 = await p.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }))
console.log('bom overflow', JSON.stringify(ov2))
await p.screenshot({ path: 'dev/.shots/r6-m-bom-result.png', fullPage: true })
await b.close()
