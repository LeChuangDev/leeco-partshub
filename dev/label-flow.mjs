import { chromium } from 'playwright'
const b=await chromium.launch({channel:'chrome',headless:true})
const p=await (await b.newContext({viewport:{width:1440,height:940}})).newPage()
const errs=[]; p.on('pageerror',e=>errs.push(e.message))
await p.goto('http://127.0.0.1:5173/#/parts'); await p.waitForTimeout(1600)
const checks=p.locator('.n-data-table-tbody .n-checkbox')
await checks.nth(0).click(); await checks.nth(1).click(); await p.waitForTimeout(300)
console.log('selected chip:', await p.locator('.table-head .chip').last().innerText())
await p.getByRole('button',{name:'打印标签'}).click(); await p.waitForTimeout(2000)
console.log('url', p.url(), 'labels', await p.locator('.label').count())
await p.goto('http://127.0.0.1:5173/#/parts'); await p.waitForTimeout(1500)
await p.locator('.n-data-table-tbody .n-data-table-tr').first().click(); await p.waitForTimeout(900)
await p.getByRole('button',{name:'打印标签'}).click(); await p.waitForTimeout(2000)
console.log('from drawer url', p.url(), 'labels', await p.locator('.label').count())
console.log('errors', errs.length?errs.join('|'):'none')
await b.close()
