import { chromium } from 'playwright'
const BASE='http://127.0.0.1:5173'
const OUT='C:/Users/zhang/Desktop/Project/Leeco PartsHub/dev/.shots'
const b=await chromium.launch({channel:'chrome',headless:true})
const errs=[]
const ctx=await b.newContext({viewport:{width:1440,height:940},deviceScaleFactor:1.25})
const p=await ctx.newPage()
p.on('pageerror',e=>errs.push(e.message))
p.on('console',m=>{if(m.type()==='error')errs.push(m.text())})
await p.goto(BASE+'/#/dashboard'); await p.waitForTimeout(2400)
await p.screenshot({path:`${OUT}/f-dash.png`})
await p.goto(BASE+'/#/parts'); await p.waitForTimeout(1600)
await p.screenshot({path:`${OUT}/f-parts.png`})
await p.goto(BASE+'/#/bom'); await p.waitForTimeout(1000)
await p.getByRole('button',{name:'载入示例'}).click(); await p.waitForTimeout(300)
await p.getByRole('button',{name:'解析并匹配库存'}).click(); await p.waitForTimeout(2000)
await p.screenshot({path:`${OUT}/f-bom.png`})
await p.goto(BASE+'/#/locations'); await p.waitForTimeout(1800)
await p.screenshot({path:`${OUT}/f-locations.png`})
await ctx.close()
const ctx2=await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:1.25})
const p2=await ctx2.newPage()
p2.on('pageerror',e=>errs.push('m:'+e.message))
await p2.goto(BASE+'/#/dashboard'); await p2.waitForTimeout(2200)
await p2.screenshot({path:`${OUT}/f-m-dash.png`})
await p2.goto(BASE+'/#/parts'); await p2.waitForTimeout(1600)
await p2.screenshot({path:`${OUT}/f-m-parts.png`})
await ctx2.close()
console.log('errors:', errs.length?errs.join(' | '):'none')
await b.close()
