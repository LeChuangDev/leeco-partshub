import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 1200, height: 1000 }, deviceScaleFactor: 1 })
const p = await ctx.newPage()
p.on('pageerror', e => console.log('ERR', e.message))
await p.goto('http://127.0.0.1:5173/#/dashboard'); await p.waitForTimeout(2200)
const ids = await p.evaluate(async () => {
  const r = await fetch('/api/parts?pageSize=8'); const j = await r.json()
  return j.data.list.map(x => x.id)
})
console.log('ids', ids.length, ids.slice(0,2))
await p.goto(`http://127.0.0.1:5173/#/labels?ids=${ids.join(',')}`)
await p.waitForTimeout(2400)
console.log('url', p.url())
console.log('labels', await p.locator('.label').count(), 'sheet', await p.locator('.sheet').count())
await p.emulateMedia({ media: 'print' })
await p.waitForTimeout(400)
console.log('after print labels', await p.locator('.label').count())
await p.screenshot({ path: 'dev/.shots/r5-labels-print.png' })
await b.close()
